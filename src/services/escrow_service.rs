pub async fn release_escrow_funds(
    pool: &PgPool,
    contract_id: Uuid,
    amount: Decimal,
    is_partial: bool,
) -> Result<(), String> {
    let mut transaction = pool.begin().await.map_err(|e| e.to_string())?;

    // Fetch contract details to get client and freelancer IDs
    let contract = sqlx::query_as!(
        Contract,
        r#"
        SELECT client_id, freelancer_id
        FROM contracts
        WHERE id = $1
        "#,
        contract_id
    )
    .fetch_one(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    // Fetch escrow account details
    let mut escrow_account = sqlx::query_as!(
        EscrowAccount,
        r#"
        SELECT id, contract_id, amount, status, dispute, release_status
        FROM escrow_accounts
        WHERE contract_id = $1
        "#,
        contract_id
    )
    .fetch_one(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    // Check for pending dispute
    if escrow_account.dispute {
        return Err("Escrow has a pending dispute. Release cannot proceed.".to_string());
    }

    // Ensure release is authorized
    let release_status: EscrowStatus = escrow_account.release_status.parse().unwrap_or(EscrowStatus::LOCKED);
    if release_status != EscrowStatus::AUTHORIZED {
        return Err("Release not authorized by the client.".to_string());
    }

    if let Some(amount) = amount {
        // Calculate fee and total release amount
        let fee = calculate_fee(amount, MembershipTier::Normal).min(1000.0);
        let total_release = amount.checked_add(fee)
        .ok_or("Amount overflow".into())?;

        // Check sufficient funds
        if escrow_account.amount < total_release {
            return Err("Insufficient funds to cover amount and fee.".to_string());
        }

        // Deduct total from escrow and update status to 'RELEASED'

        escrow_account.amount -= total_release;

        sqlx::query!(
            r#"
            UPDATE escrow_accounts
            SET amount = amount - $1,
                release_status = $2
            WHERE contract_id = $3
            "#,
            total_release,
            escrow_account.amount
            EscrowStatus::RELEASED.to_string(),
            contract_id
        )
        .execute(&mut *transaction)
        .await
        .map_err(|e| e.to_string())?;

        // Transfer amount to freelancer's account
        sqlx::query!(
            r#"
            UPDATE accounts
            SET balance = balance + $1
            WHERE id = $2
            "#,
            amount,
            contract.freelancer_id
        )
        .execute(&mut *transaction)
        .await
        .map_err(|e| e.to_string())?;

        update_balance(&mut *transaction, contract.freelancer_id, amount).await?;
        update_balance(&mut *transaction, PLATFORM_ACCOUNT_ID, fee).await?;
    
     // Transfer fee to platform's account (assuming platform ID is 1)
        const PLATFORM_ACCOUNT_ID: i32 = 1;
        record_payment_history(
            &mut *transaction,
            escrow_account.id,
            amount,
            if is_partial { "Partial Release" } else { "Full Release" },
        ).await?;
    
        record_payment_history(
            &mut *transaction,
            escrow_account.id,
            fee,
            "Platform Fee",
        ).await?;
    
        transaction.commit().await.map_err(|e| e.to_string());

        // Notify the freelancer that funds have been released
        notify_freelancer_of_release(contract.freelancer_id, amount, is_partial).await?;
    }

    transaction.commit().await.map_err(|e| e.to_string())
}

