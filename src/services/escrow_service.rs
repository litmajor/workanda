// Types
#[derive(Debug)]
pub enum DisputeResolution {
    FullReleaseToFreelancer(Decimal),
    PartialRelease { freelancer: Decimal, client: Decimal },
    RefundToClient(Decimal),
    CustomSplit { freelancer: Decimal, client: Decimal, platform: Decimal },
}

impl DisputeResolution {
    fn transfers(&self) -> Vec<(Recipient, Decimal)> {
        match self {
            Self::FullReleaseToFreelancer(a) => vec![(Recipient::Freelancer, *a)],
            Self::PartialRelease { freelancer, client } => vec![
                (Recipient::Freelancer, *freelancer),
                (Recipient::Client, *client),
            ],
            Self::RefundToClient(a) => vec![(Recipient::Client, *a)],
            Self::CustomSplit { freelancer, client, platform } => vec![
                (Recipient::Freelancer, *freelancer),
                (Recipient::Client, *client),
                (Recipient::Platform, *platform),
            ],
        }
    }
}

#[derive(Debug)]
enum Recipient {
    Freelancer,
    Client,
    Platform,
}

