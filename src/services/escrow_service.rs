async fn send_refund_notification(
    transaction: &mut sqlx::Transaction<'_, sqlx::Postgres>,
    client_id: i32,
    freelancer_id: i32,
    amount: Decimal,
    reason: &str,
) -> Result<(), String> {
    // Send notification to client
    sqlx::query!(
        r#"
        INSERT INTO notifications (user_id, type, title, message, created_at)
        VALUES ($1, 'refund', 'Refund Processed', $2, NOW())
        "#,
        client_id,
        format!("Your refund of ${} has been processed. Reason: {}", amount, reason)
    )
    .execute(&mut **transaction)
    .await
    .map_err(|e| e.to_string())?;

    // Send notification to freelancer
    sqlx::query!(
        r#"
        INSERT INTO notifications (user_id, type, title, message, created_at)
        VALUES ($1, 'refund', 'Refund Issued', $2, NOW())
        "#,
        freelancer_id,
        format!("A refund of ${} has been issued for the contract.", amount)
    )
    .execute(&mut **transaction)
    .await
    .map_err(|e| e.to_string())?;

    Ok(())
}

pub async fn get_escrow_account_details(
    pool: &PgPool,
    contract_id: Uuid,
) -> Result<EscrowDetails, String> {
    #[derive(Debug, sqlx::FromRow)]
    struct EscrowDetails {
        balance: Decimal,
        status: String,
        dispute: bool,
        payment_history: Vec<PaymentHistory>,
    }

    let escrow_details: EscrowDetails = sqlx::query_as!(
        EscrowDetails,
        r#"
        SELECT 
            e.amount AS balance,
            e.status,
            e.dispute,
            ph.amount,
            ph.transaction_type,
            ph.timestamp
        FROM escrow_accounts e
        LEFT JOIN payment_history ph ON e.id = ph.escrow_account_id
        WHERE e.contract_id = $1
        "#,
        contract_id
    )
    .fetch_all(pool)
    .await
    .map_err(|e| e.to_string())?
    .into_iter()
    .fold(
        EscrowDetails {
            balance: Decimal::default(),
            status: "".into(),
            dispute: false,
            payment_history: vec![],
        },
        |mut acc, row| {
            acc.balance = row.balance;
            acc.status = row.status;
            acc.dispute = row.dispute;
            acc.payment_history.push(PaymentHistory {
                amount: row.amount,
                transaction_type: row.transaction_type,
                timestamp: row.timestamp,
            });
            acc
        },
    );

    Ok(escrow_details)
}

