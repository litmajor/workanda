pub async fn resolve_dispute(
    pool: &PgPool,
    contract_id: Uuid,
    resolution: DisputeResolution,
) -> Result<(), String> {
    let mut transaction = pool.begin().await.map_err(|e| e.to_string())?;
    

    let contract = get_contract_with_escrow(&mut *transaction, contract_id).await?;
    let escrow_account = get_escrow_account(&mut *transaction, contract_id).await?;

    
    if !escrow_account.dispute {
        return Err("No event disputes".into());
    }

    // Fetch contract and escrow details
    let contract = sqlx::query_as!(
        Contract,
        r#"
        SELECT client_id, freelancer_id
        FROM contracts
        WHERE id = $1
        "#,
        contract_id
    )
    .fetch_one(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    let escrow_account = sqlx::query_as!(
        EscrowAccount,
        r#"
        SELECT id, amount, status, dispute
        FROM escrow_accounts
        WHERE contract_id = $1
        "#,
        contract_id
    )
    .fetch_one(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    if !escrow_account.dispute {
        return Err("No active dispute to resolve.".to_string());
    }

    // Calculate total transferred and validate
    let (total_transferred, transaction_types) = match resolution {
        DisputeResolution::FullReleaseToFreelancer(amount) => {
            if escrow_account.amount < amount {
                return Err("Insufficient funds in escrow account.".to_string());
            }
            (amount, vec![("Freelancer", amount)])
        }
        DisputeResolution::PartialReleaseToFreelancer(freelancer, client) => {
            let total = freelancer + client;
            if escrow_account.amount < total {
                return Err("Insufficient funds in escrow account.".to_string());
            }
            (total, vec![("Freelancer", freelancer), ("Client", client)])
        }
        DisputeResolution::RefundToClient(amount) => {
            if escrow_account.amount < amount {
                return Err("Insufficient funds in escrow account.".to_string());
            }
            (amount, vec![("Client", amount)])
        }
        DisputeResolution::CustomSplit { freelancer, client, platform } => {
            let total = freelancer + client + platform;
            if escrow_account.amount < total {
                return Err("Insufficient funds in escrow account.".to_string());
            }
            (total, vec![("Freelancer", freelancer), ("Client", client), ("Platform", platform)])
        }
    };

    // Perform transfers and log history
    for (recipient, amount) in  resolution.transfers() {
        match recipient {
            "Freelancer" => {
                transfer_to_freelancer(&mut *transaction, contract.freelancer_id, *amount).await?;
                record_payment_history(
                    &mut *transaction,
                    escrow_account.id,
                    *amount,
                    "Dispute Resolution Freelancer",
                    contract.freelancer_id,
                ).await?;
            }
            "Client" => {
                transfer_to_client(&mut *transaction, contract.client_id, *amount).await?;
                record_payment_history(
                    &mut *transaction,
                    escrow_account.id,
                    *amount,
                    "Dispute Resolution Client",
                    contract.client_id,
                ).await?;
            }
            "Platform" => {
                transfer_to_platform(&mut *transaction, *amount).await?;
                record_payment_history(
                    &mut *transaction,
                    escrow_account.id,
                    *amount,
                    "Dispute Resolution Platform",
                    get_platform_account_id(&mut *transaction).await?,
                ).await?;
            }
            _ => unreachable!(),
        }
    }

    // Update escrow balance and status
    sqlx::query!(
        r#"
        UPDATE escrow_accounts
        SET amount = amount - $1,
            dispute = FALSE,
            status = 'RESOLVED'
        WHERE contract_id = $2
        "#,
        total_transferred,
        contract_id
    )
    .execute(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    transaction.commit().await.map_err(|e| e.to_string())
}

