pub async fn release_funds_for_deliverable(
    pool: &PgPool,
    deliverable_id: u32,
) -> Result<(), String> {
    let mut transaction = pool.begin().await.map_err(|e| e.to_string())?;

    // Fetch deliverable details
    let deliverable = sqlx::query_as!(
        Deliverable,
        r#"
        SELECT id, contract_id, amount, status
        FROM deliverables
        WHERE id = $1
        "#,
        deliverable_id
    )
    .fetch_one(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    if deliverable.status != "AUTHORIZED" {
        return Err("Deliverable is not authorized for release.".to_string());
    }

    // Fetch contract and escrow details
    let contract = sqlx::query_as!(
        Contract,
        r#"
        SELECT client_id, freelancer_id
        FROM contracts
        WHERE id = $1
        "#,
        deliverable.contract_id
    )
    .fetch_one(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    let escrow_account = sqlx::query_as!(
        EscrowAccount,
        r#"
        SELECT id, amount
        FROM escrow_accounts
        WHERE contract_id = $1
        "#,
        deliverable.contract_id
    )
    .fetch_one(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    if escrow_account.amount < deliverable.amount {
        return Err("Insufficient funds in escrow account.".to_string());
    }

    // Deduct amount from escrow account
    let updated_escrow_balance = escrow_account.amount - deliverable.amount;
    sqlx::query!(
        r#"
        UPDATE escrow_accounts
        SET amount = $1
        WHERE contract_id = $2
        "#,
        updated_escrow_balance,
        deliverable.contract_id
    )
    .execute(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    // Transfer amount to freelancer's account
    update_balance(&mut *transaction, contract.freelancer_id, deliverable.amount).await?;

    // Record payment history
    record_payment_history(
        &mut *transaction,
        escrow_account.id,
        deliverable.amount,
        "Deliverable Release",
        contract.freelancer_id,
    ).await?;

    // Update deliverable status to RELEASED
    sqlx::query!(
        r#"
        UPDATE deliverables
        SET status = 'RELEASED', updated_at = NOW()
        WHERE id = $1
        "#,
        deliverable_id
    )
    .execute(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    transaction.commit().await.map_err(|e| e.to_string())
}

