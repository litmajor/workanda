// Function to lock funds in the escrow account
pub async fn lock_funds_in_escrow(
    pool: &PgPool,
    contract_id: Uuid,
    amount: Decimal,
) -> Result<(), String> {
    let mut transaction = pool.begin().await.map_error(|e| e.to_string())?;

    // Fetch the escrow account by contract_id
    let mut escrow_account = sqlx::query_as!(
        EscrowAccount,
        r#"
        SELECT id, contract_id, amount, status, dispute
        FROM escrow_accounts
        WHERE contract_id = $1
        "#,
        contract_id
    )
    .fetch_one(&mut *transaction)
    .await
    .map_err(|e| e.to_string())?;

    if escrow_account.status != EscrowStatus::Pending {
        return Err("Cannot lock funds for non-pending escrow".into());
    }

        // Update the escrow balance
    let updated_balance = escrow_account.amount.checked_add(amount)
        .ok_or("Decimal overflow on fund locking".into())?;


    let update_result = sqlx::query!(
        r#"
        UPDATE escrow_accounts
        SET amount = $1
        WHERE contract_id = $2
        "#,
        updated_balance,
        contract_id
    )
    .execute(&mut *transaction)
    .await;

    update_result
        .map_err(|e| e.to_string())?;

    // Record the payment history
    let _ = sqlx::query!(
        r#"
        INSERT INTO payment_history (escrow_account_id, amount, transaction_type)
        VALUES ($1, $2, 'Fund Lock')
        "#,
        escrow_account.id,
        amount,
        "Deposit"
    )
    .execute(pool)
    .await
    .map_err(|e| e.to_string())?;

    transaction.commit().await.map_err(|e| e.to_string())
}

