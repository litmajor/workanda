// Function to create escrow account
pub async fn create_escrow_account(
    pool: &PgPool,
    contract_id: Uuid,
    amount: Decimal,
) -> Result<EscrowAccount, sqlx::Error> {
    let new_escrow = EscrowAccount {
        id: 0,
        contract_id,
        amount,
        status: EscrowStatus::Pending,
        dispute: None,
    };

    info!("Creating escrow account for contract_id: {} with amount: {}", contract_id, amount);

    let result = sqlx::query_as!(
        EscrowAccount,
        r#"
        INSERT INTO escrow_accounts (contract_id, amount, status)
        VALUES ($1, $2, $3)
        RETURNING id, contract_id, amount, status, dispute
        "#,
        contract_id,
        amount,
        new_escrow.status as EscrowStatus
    )
    .fetch_one(pool)
    .await;

    match result {
        Ok(escrow_account) => {
            info!("Escrow account created with ID: {}", escrow_account.id);
            Ok(escrow_account)
        },
        Err(e) => {
            error!("Failed to create escrow account: {:?}", e);
            Err(e)
        }
    }
}


