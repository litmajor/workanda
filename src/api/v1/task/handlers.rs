pub async fn mark_task_as_completed_handler(
    pool: web::Data<PgPool>,
    task_id: web::Path<u32>,
) -> Result<HttpResponse, ApiError> {
    let rows_affected = sqlx::query(
        r#"
        UPDATE tasks
        SET status = 'Completed', updated_at = NOW()
        WHERE id = $1 AND status != 'Completed'
        "#,
    )
    .bind(*task_id)
    .execute(pool.as_ref())
    .await?
    .rows_affected();

    if rows_affected == 0 {
        return Err(ApiError::NotFound(format!("Task with ID {} not found or already completed", task_id)));
    }

    Ok(HttpResponse::Ok().body("Task marked as completed"))
}